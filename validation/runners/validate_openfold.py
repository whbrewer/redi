#!/usr/bin/env python3
"""
Compare REDI OpenFold output against features generated by OpenFold's own
data_pipeline functions (make_mmcif_features + make_msa_features).

Usage:
    source /opt/venvs/drai/bin/activate
    python scripts/validate_openfold.py \\
        --data_dir /opt/drai/openfold_data \\
        --redi_dir  <redi output dir>       \\
        [--proteins 1CRN 1UBQ 1BTA]         \\
        [--style rich|json]                  \\
        [--out validate_results/openfold_validate.json]
"""

import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, "/opt/drai/openfold")


# ---------------------------------------------------------------------------
# OpenFold ground-truth generation
# ---------------------------------------------------------------------------

def _of_features_for_protein(pdb_id: str, data_dir: Path) -> dict:
    """Generate features using OpenFold's own pipeline functions."""
    from openfold.data import parsers
    from openfold.data import mmcif_parsing
    from openfold.data.data_pipeline import (
        make_sequence_features,
        make_mmcif_features,
        make_msa_features,
    )

    cif_path  = data_dir / "pdb" / f"{pdb_id}.cif"
    align_dir = data_dir / "alignments" / pdb_id

    # Structure + sequence features
    with open(cif_path) as fh:
        mmcif_string = fh.read()
    parse_result = mmcif_parsing.parse(file_id=pdb_id, mmcif_string=mmcif_string)
    if parse_result.mmcif_object is None:
        raise RuntimeError(f"mmcif_parsing failed for {pdb_id}: {parse_result.errors}")
    mmcif_obj = parse_result.mmcif_object
    chain_id  = next(iter(mmcif_obj.chain_to_seqres))
    feats = make_mmcif_features(mmcif_obj, chain_id)

    # MSA features
    msas = []
    for a3m_name in ["uniref.a3m", "bfd.mgnify30.metaeuk30.smag30.a3m"]:
        a3m_path = align_dir / a3m_name
        if a3m_path.exists():
            # Strip null bytes that ColabFold API may embed in the file
            text = a3m_path.read_text(errors="replace").replace("\x00", "")
            msas.append(parsers.parse_a3m(text))

    if not msas:
        # No alignments — query-only single-row MSA
        seq = mmcif_obj.chain_to_seqres[chain_id]
        msas = [parsers.parse_a3m(f">{pdb_id}\n{seq}\n")]

    feats.update(make_msa_features(msas))
    return feats


# ---------------------------------------------------------------------------
# Per-feature comparison
# ---------------------------------------------------------------------------

# Features we can meaningfully compare (numeric arrays present in both outputs)
COMPARABLE_FEATURES = [
    "aatype",
    "residue_index",
    "seq_length",
    "between_segment_residues",
    "msa",
    "deletion_matrix_int",
    "num_alignments",
    "all_atom_positions",
    "all_atom_mask",
    "resolution",
    "is_distillation",
]


def _compare_feature(name: str, of_val, redi_val) -> dict:
    result = {"feature": name, "match": False, "note": ""}

    # Skip object arrays (domain_name, sequence, release_date)
    if hasattr(of_val, "dtype") and of_val.dtype == object:
        result["match"] = True
        result["note"] = "skipped (object dtype)"
        return result

    if redi_val is None:
        result["note"] = "missing from REDI output"
        return result

    try:
        of_arr  = np.asarray(of_val,  dtype=np.float64)
        rdi_arr = np.asarray(redi_val, dtype=np.float64)
    except Exception as e:
        result["note"] = f"cast error: {e}"
        return result

    if of_arr.shape != rdi_arr.shape:
        result["note"] = f"shape mismatch: OF={of_arr.shape} REDI={rdi_arr.shape}"
        return result

    if of_arr.size == 0:
        result["match"] = True
        result["note"] = "empty array"
        return result

    max_abs = float(np.max(np.abs(of_arr - rdi_arr)))
    corr = float(np.corrcoef(of_arr.ravel(), rdi_arr.ravel())[0, 1]) if of_arr.size > 1 else 1.0

    result["shape"]        = list(of_arr.shape)
    result["max_abs_diff"] = round(max_abs, 6)
    result["corr"]         = round(corr, 6) if not np.isnan(corr) else None
    result["match"]        = max_abs < 1e-4

    if not result["match"]:
        result["note"] = f"max|diff|={max_abs:.4g}"

    return result


def compare_protein(pdb_id: str, data_dir: Path, redi_dir: Path) -> dict:
    # Locate the REDI NPZ (may be in train/, val/, or test/)
    npz_path = None
    for split in ("train", "val", "test"):
        p = redi_dir / split / f"{pdb_id}.npz"
        if p.exists():
            npz_path = p
            break
    if npz_path is None:
        return {"pdb_id": pdb_id, "error": "NPZ not found in REDI output"}

    try:
        of_feats = _of_features_for_protein(pdb_id, data_dir)
    except Exception as e:
        return {"pdb_id": pdb_id, "error": f"OpenFold pipeline failed: {e}"}

    redi_feats = dict(np.load(npz_path, allow_pickle=False))

    comparisons = []
    for feat in COMPARABLE_FEATURES:
        of_val   = of_feats.get(feat)
        redi_val = redi_feats.get(feat)
        if of_val is None:
            comparisons.append({"feature": feat, "match": True, "note": "not produced by OF pipeline"})
            continue
        comparisons.append(_compare_feature(feat, of_val, redi_val))

    n_match = sum(1 for c in comparisons if c["match"])
    return {
        "pdb_id":    pdb_id,
        "n_match":   n_match,
        "n_total":   len(comparisons),
        "all_match": n_match == len(comparisons),
        "features":  comparisons,
    }


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description="Validate REDI OpenFold output against OpenFold's own pipeline"
    )
    parser.add_argument("--data_dir", required=True,
                        help="OpenFold data root (has fasta/, pdb/, alignments/)")
    parser.add_argument("--redi_dir", required=True,
                        help="REDI output directory (has train/, val/, test/)")
    parser.add_argument("--proteins", nargs="+", default=None,
                        help="Protein IDs to compare (default: all with MSA alignments)")
    parser.add_argument("--style", choices=["rich", "json"], default="rich")
    parser.add_argument("--out", default=None,
                        help="Save JSON results to this path")
    args = parser.parse_args()

    data_dir = Path(args.data_dir)
    redi_dir = Path(args.redi_dir)

    if args.proteins:
        pdb_ids = args.proteins
    else:
        align_dir = data_dir / "alignments"
        pdb_ids = sorted(p.name for p in align_dir.iterdir() if p.is_dir()) \
                  if align_dir.exists() else []
        if not pdb_ids:
            print("No alignment directories found. Use --proteins to specify.", file=sys.stderr)
            sys.exit(1)

    results = []
    for pdb_id in pdb_ids:
        if args.style == "rich":
            print(f"  {pdb_id}...", end=" ", flush=True)
        r = compare_protein(pdb_id, data_dir, redi_dir)
        results.append(r)
        if args.style == "rich":
            if "error" in r:
                print(f"ERROR: {r['error']}")
            elif r["all_match"]:
                print(f"✓  {r['n_match']}/{r['n_total']} features match")
            else:
                fails = [c["feature"] for c in r["features"] if not c["match"]]
                print(f"✗  {r['n_match']}/{r['n_total']}  mismatches: {fails}")

    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        with open(args.out, "w") as fh:
            json.dump(results, fh, indent=2)
        if args.style == "rich":
            print(f"\nResults saved → {args.out}")

    if args.style == "json":
        print(json.dumps(results, indent=2))
        return

    # Summary
    ok     = sum(1 for r in results if r.get("all_match"))
    errors = sum(1 for r in results if "error" in r)
    total  = len(results)
    print()
    print("=" * 55)
    print(f"  {ok}/{total} proteins fully matched  ({errors} errors)")

    feat_fails: dict = {}
    for r in results:
        for c in r.get("features", []):
            if not c["match"] and "skipped" not in c.get("note", "") \
                    and "not produced" not in c.get("note", ""):
                feat_fails.setdefault(c["feature"], []).append(
                    f"{r['pdb_id']}: {c.get('note', '')}"
                )
    if feat_fails:
        print()
        print("  Feature mismatches:")
        for feat, notes in sorted(feat_fails.items()):
            print(f"    {feat}:")
            for n in notes[:5]:
                print(f"      {n}")
    print("=" * 55)


if __name__ == "__main__":
    main()
