"""
redi/discover/report.py — render processing_plan.md from FileDiscovery results.
"""

from __future__ import annotations

import datetime
from pathlib import Path

from redi.discover.processors import FileDiscovery


def render_processing_plan(
    discoveries: list[FileDiscovery],
    output_path: Path,
) -> None:
    """Write a human-readable ``processing_plan.md`` to *output_path*.

    Args:
        discoveries: List of :class:`~redi.discover.processors.FileDiscovery`
            objects produced by the processor registry.
        output_path: Destination file path (will be created/overwritten).
    """
    lines: list[str] = []
    now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")

    lines += [
        "# Processing Plan",
        "",
        f"Generated by `redi discover` on {now}",
        "",
        "---",
        "",
        "## Summary",
        "",
    ]

    # Summary table
    lines += [
        "| File | Type | Size | Preprocessing Steps |",
        "|------|------|------|---------------------|",
    ]
    for d in discoveries:
        fname = Path(d.file_path).name
        size_str = _fmt_size(d.file_size_bytes)
        n_steps = len(d.preprocessing_steps)
        step_label = str(n_steps) if n_steps else "0 (reference only)"
        lines.append(f"| `{fname}` | {d.file_type} | {size_str} | {step_label} |")

    lines += ["", "---", ""]

    # Per-file sections
    for d in discoveries:
        lines += _render_file_section(d)

    output_path.write_text("\n".join(lines), encoding="utf-8")


# ---------------------------------------------------------------------------
# Section renderers
# ---------------------------------------------------------------------------

def _render_file_section(d: FileDiscovery) -> list[str]:
    fname = Path(d.file_path).name
    lines: list[str] = [
        f"## File: `{fname}`",
        "",
        f"**Type:** {d.file_type}  ",
        f"**Path:** `{d.file_path}`  ",
        f"**Size:** {_fmt_size(d.file_size_bytes)}",
        "",
    ]

    if "error" in d.metadata:
        lines += [f"> Could not analyze file: {d.metadata['error']}", "", "---", ""]
        return lines

    if d.file_type == "CSV":
        lines += _render_csv_section(d)
    elif d.file_type == "Markdown":
        lines += _render_markdown_section(d)
    elif d.file_type == "NetCDF":
        lines += _render_netcdf_section(d)
    else:
        if d.metadata:
            lines += ["**Metadata:**", ""]
            for k, v in d.metadata.items():
                lines.append(f"- **{k}:** {v}")
            lines.append("")

    if d.preprocessing_steps:
        lines += ["### Suggested Preprocessing Steps", ""]
        for i, step in enumerate(d.preprocessing_steps, 1):
            lines += [
                f"{i}. **{step.name}**",
                f"   - *Rationale:* {step.rationale}",
                f"   - *Method:* {step.suggested_method}",
            ]
        lines.append("")
    elif d.file_type != "Markdown":
        lines += ["*No preprocessing steps suggested.*", ""]

    lines += ["---", ""]
    return lines


def _render_csv_section(d: FileDiscovery) -> list[str]:
    meta = d.metadata
    shape = meta.get("shape", [])
    col_titles = meta.get("column_titles", [])
    col_types = meta.get("column_types", {})
    col_stats = meta.get("column_stats", {})

    lines: list[str] = []

    if shape:
        lines.append(f"**Shape:** {shape[0]:,} rows × {shape[1]} columns")
        lines.append("")

    if col_titles:
        lines += ["### Columns", ""]
        lines += [
            "| Column | Type | Stats / Info |",
            "|--------|------|--------------|",
        ]
        for col in col_titles:
            ctype = col_types.get(col, "unknown")
            stats = col_stats.get(col, {})
            stats_str = _fmt_stats(ctype, stats)
            lines.append(f"| `{col}` | {ctype} | {stats_str} |")
        lines.append("")

    return lines


def _render_netcdf_section(d: FileDiscovery) -> list[str]:
    meta = d.metadata
    lines: list[str] = []

    dims = meta.get("dimensions", {})
    if dims:
        dim_str = " × ".join(f"{k}={v}" for k, v in dims.items())
        lines.append(f"**Dimensions:** {dim_str}")
        lines.append("")

    lat_range = meta.get("lat_range")
    lon_range = meta.get("lon_range")
    res = meta.get("resolution_deg")
    if lat_range and lon_range:
        lines.append(f"**Spatial:** lat {lat_range[0]}°–{lat_range[1]}°, lon {lon_range[0]}°–{lon_range[1]}°" +
                     (f" at {res}° resolution" if res else ""))
        lines.append("")

    t_start = meta.get("time_start")
    t_end = meta.get("time_end")
    t_steps = meta.get("time_steps")
    if t_start and t_end:
        lines.append(f"**Time:** {t_start} → {t_end} ({t_steps} timesteps)")
        lines.append("")

    var_info = meta.get("variable_info", {})
    if var_info:
        lines += ["### Variables", ""]
        lines += ["| Variable | Shape | Units | Long Name |",
                  "|----------|-------|-------|-----------|"]
        for var, info in var_info.items():
            shape = "×".join(str(s) for s in info.get("shape", []))
            units = info.get("units", "—")
            long_name = info.get("long_name", "—")
            lines.append(f"| `{var}` | {shape} | {units} | {long_name} |")
        lines.append("")

    return lines


def _render_markdown_section(d: FileDiscovery) -> list[str]:
    meta = d.metadata
    lines: list[str] = ["*(Reference document — no preprocessing suggested)*", ""]

    headings = meta.get("headings", [])
    if headings:
        lines += ["### Table of Contents", ""]
        for h in headings:
            indent = "  " * (h["level"] - 1)
            lines.append(f"{indent}- {'#' * h['level']} {h['text']}")
        lines.append("")

    file_refs = meta.get("file_references", [])
    if file_refs:
        lines += ["### Referenced Files", ""]

        groups = meta.get("file_groups", {})

        by_heading = groups.get("by_heading", {})
        if by_heading:
            lines.append("**By Heading:**")
            lines.append("")
            for heading, refs in by_heading.items():
                unique_refs = list(dict.fromkeys(refs))
                lines.append(f"- *{heading}:* " + ", ".join(f"`{r}`" for r in unique_refs))
            lines.append("")

        by_list = groups.get("by_list", [])
        if by_list:
            lines.append("**By List:**")
            lines.append("")
            for group in by_list:
                unique = list(dict.fromkeys(group))
                lines.append("- " + ", ".join(f"`{r}`" for r in unique))
            lines.append("")

        by_adjacency = groups.get("by_adjacency", [])
        if by_adjacency:
            lines.append("**By Adjacency:**")
            lines.append("")
            for group in by_adjacency:
                unique = list(dict.fromkeys(group))
                lines.append("- " + ", ".join(f"`{r}`" for r in unique))
            lines.append("")

    return lines


# ---------------------------------------------------------------------------
# Formatting helpers
# ---------------------------------------------------------------------------

def _fmt_size(n: int) -> str:
    if n < 1024:
        return f"{n} B"
    if n < 1024 ** 2:
        return f"{n / 1024:.1f} KB"
    if n < 1024 ** 3:
        return f"{n / 1024**2:.1f} MB"
    return f"{n / 1024**3:.2f} GB"


def _fmt_stats(col_type: str, stats: dict) -> str:
    if col_type == "numeric":
        parts = []
        if stats.get("mean") is not None:
            parts.append(f"mean={stats['mean']}")
        if stats.get("std") is not None:
            parts.append(f"std={stats['std']}")
        if stats.get("min") is not None and stats.get("max") is not None:
            parts.append(f"range=[{stats['min']}, {stats['max']}]")
        if stats.get("pct_missing", 0) > 0:
            parts.append(f"{stats['pct_missing']}% missing")
        return ", ".join(parts) if parts else "—"

    if col_type == "categorical":
        n_unique = stats.get("n_unique", "?")
        top = stats.get("top_values", {})
        top_str = "; ".join(f"{k}: {v}" for k, v in list(top.items())[:3])
        pct = stats.get("pct_missing", 0)
        s = f"{n_unique} unique values"
        if top_str:
            s += f"; top: {top_str}"
        if pct > 0:
            s += f"; {pct}% missing"
        return s

    if col_type == "boolean":
        vc = stats.get("value_counts", {})
        return ", ".join(f"{k}: {v}" for k, v in vc.items())

    if col_type == "datetime":
        pct = stats.get("pct_missing", 0)
        return f"{pct}% missing" if pct > 0 else "datetime"

    return "—"
